# =====================================================================
#  make-installer.ps1 —— 一键打包 IExpress 自解压安装包
#  产物: dist\iflytek-sinkhole-setup.exe
#        双击 → 解压 → UAC 提权 → 铺开目录结构 → 自动跑 setup-on-this-pc.ps1
#  用法: .\make-installer.ps1             捆绑 runtime\node.exe(推荐,离线可装)
#        .\make-installer.ps1 -NoRuntime  不捆绑 Node(新机器安装时用 -BundleRuntime 下载)
#        .\make-installer.ps1 -KeepStaging 保留中间目录便于排查
#  已知约束(实测得出):
#   - IExpress 的 /N 不接受带引号的路径 → 构建目录必须无空格(自动选 TEMP,
#     TEMP 含空格时回退 C:\iflytek-si-build,两者都含空格会报错提示)
#   - SED 必须 GBK(936) 编码,否则中文文件名的文件找不到 → 只能在中文 Windows 上构建
#   - IExpress 解压会拍平子目录 → 由 install.cmd(GBK)按扩展名重建
#     public\ / certs\ / runtime\ 结构;通配符拷贝,脚本内零中文件名
#  安装期环境变量(可选,主要给自动化测试):
#     INSTALL_DIR=目标目录(默认 %ProgramFiles%\iflytek-sinkhole)
#     SKIP_SETUP=1 跳过 setup-on-this-pc.ps1(只铺文件)
#     AUTO_EXIT=1  结束不按任意键(不弹 pause)
# =====================================================================
param([switch]$NoRuntime, [switch]$KeepStaging)
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$utf8Bom = New-Object System.Text.UTF8Encoding($true)

function Step($t) { Write-Host "`n==> $t" -ForegroundColor Cyan }
function OK($t)   { Write-Host "  [OK] $t" -ForegroundColor Green }
function Warn($t) { Write-Host "  [!] $t" -ForegroundColor Yellow }
function Fail($t) { Write-Host "  [X] $t" -ForegroundColor Red }

# ---------- 0) 构建目录(必须无空格,IExpress /N 不吃引号) ----------
$staging = Join-Path $env:TEMP 'iflytek-si-build'
if ($staging -match '\s') { $staging = "$env:SystemDrive\iflytek-si-build" }
if ($staging -match '\s') { throw "构建路径含空格且无可用回退:TEMP=$env:TEMP 请把 TEMP 改到无空格路径" }
Step "准备暂存目录 $staging"
if (Test-Path $staging) { Remove-Item $staging -Recurse -Force }
New-Item -ItemType Directory -Path $staging | Out-Null
OK '暂存目录就绪'

# ---------- 1) 收集载荷(全部拍平进暂存目录) ----------
Step '收集部署文件'
$rootFiles = Get-ChildItem $root -File
if (-not ($rootFiles.Name -contains 'index.js')) { throw 'index.js 缺失,请在项目根目录运行' }
Copy-Item -Path $rootFiles.FullName -Destination $staging
if (-not (Test-Path (Join-Path $root 'public\index.html'))) { throw 'public\index.html 缺失,部署包不完整' }
Copy-Item (Join-Path $root 'public\*.html') $staging
$cer = Join-Path $root 'certs\iflytek.cer'
if (Test-Path $cer) { Copy-Item $cer $staging } else { Warn 'certs\iflytek.cer 缺失:包内将不含设备信任证书(install 后 setup 会重新生成,设备需重装证书)' }
if ($NoRuntime) { Warn '按 -NoRuntime 不捆绑 Node:新机器安装时运行 setup-on-this-pc.ps1 -BundleRuntime 下载' }
else {
  $rtNode = Join-Path $root 'runtime\node.exe'
  if (Test-Path $rtNode) { Copy-Item $rtNode $staging; OK "捆绑便携 Node ($([int]((Get-Item $rtNode).Length / 1MB)) MB)" }
  else { Warn 'runtime\node.exe 不存在:包内将不含 Node(新机器用 setup -BundleRuntime 下载)' }
}
OK "载荷文件数: $((Get-ChildItem $staging -File).Count)"

# ---------- 2) 生成 install.cmd(GBK 编码;cmd 中文输出 + 通配符重建目录) ----------
Step '生成 install.cmd'
$installCmd = @'
@echo off
rem iflytek-sinkhole installer payload (generated by make-installer.ps1)
chcp 936 >nul 2>&1
title iflytek-sinkhole Setup
setlocal EnableExtensions
set "SRC=%~dp0"
if defined INSTALL_DIR (set "DST=%INSTALL_DIR%") else set "DST=%ProgramFiles%\iflytek-sinkhole"
if defined ELEVATED goto main
net session >nul 2>&1
if errorlevel 1 goto elevate

:main
echo.
echo [iflytek-sinkhole] 安装目录: %DST%
if not exist "%DST%" mkdir "%DST%"
for %%d in (public certs runtime logs storage) do if not exist "%DST%\%%d" mkdir "%DST%\%%d"
echo [1/3] 复制文件...
copy /y "%SRC%*.js" "%DST%\" >nul
copy /y "%SRC%*.ps1" "%DST%\" >nul
copy /y "%SRC%*.json" "%DST%\" >nul
copy /y "%SRC%*.md" "%DST%\" >nul
copy /y "%SRC%*.xml" "%DST%\" >nul
copy /y "%SRC%*.html" "%DST%\public\" >nul
copy /y "%SRC%*.cer" "%DST%\certs\" >nul
if exist "%SRC%node.exe" copy /y "%SRC%node.exe" "%DST%\runtime\" >nul
if exist "%SRC%.gitignore" copy /y "%SRC%.gitignore" "%DST%\" >nul
for %%f in ("%SRC%*.cmd") do if /i not "%%~nxf"=="install.cmd" copy /y "%%~f" "%DST%\" >nul
if not exist "%DST%\index.js" goto copyfail
if not exist "%DST%\public\index.html" goto copyfail
echo [2/3] 校验通过: index.js / public\index.html
if exist "%SRC%node.exe" if not exist "%DST%\runtime\node.exe" echo [警告] runtime\node.exe 拷贝失败
echo [3/3] 运行环境安装(setup-on-this-pc.ps1: 证书/防火墙/开机自启/启动服务)...
if defined SKIP_SETUP (echo     已按 SKIP_SETUP=1 跳过) else powershell -NoProfile -ExecutionPolicy Bypass -File "%DST%\setup-on-this-pc.ps1"
echo.
echo [完成] 已安装到 %DST%
echo   设备入口: 浏览器打开 http://iflytek.com (设备需先按 操作教程.md 走本机 DNS)
echo   本机入口: 双击「中继站(管理员)」快捷方式,或 %DST%\打开中继站(管理员).cmd
echo   卸载:     %DST%\uninstall-on-this-pc.ps1
goto end

:copyfail
echo [失败] 关键文件没复制到位(安装目录不可写,或安装包损坏)。请用管理员身份重跑。
goto end

:elevate
set ELEVATED=1
echo 需要管理员权限,弹出 UAC 后请点「是」...
powershell -NoProfile -Command "Start-Process -FilePath '%~f0' -Verb RunAs -Wait"
if errorlevel 1 goto cancelled
exit /b

:cancelled
echo.
echo 已取消 UAC 授权,安装未完成。
if not defined AUTO_EXIT pause
exit /b 1

:end
echo.
if not defined AUTO_EXIT pause
exit /b 0
'@
[IO.File]::WriteAllText((Join-Path $staging 'install.cmd'), $installCmd, [Text.Encoding]::GetEncoding(936))
OK 'install.cmd 已生成(GBK)'

# ---------- 3) 生成 SED(GBK;文件清单在写 build.sed 之前枚举) ----------
Step '生成 SED 指令文件'
$exePath = Join-Path $staging 'iflytek-sinkhole-setup.exe'
$sedLines = @(
  '[Version]', 'Class=IEXPRESS', 'SEDVersion=3.0',
  '[Options]',
  'PackagePurpose=InstallApp',
  'ShowInstallProgramWindow=1',
  'HideExtractAnimation=0',
  'UseLongFileName=1',
  'InsideCompressed=1',
  'CAB_FixedSize=0',
  'RebootMode=N',
  'InstallPrompt=',
  'DisplayLicense=',
  'FinishMessage=',
  "TargetName=$exePath",
  'FriendlyName=iflytek-sinkhole Setup',
  'AppLaunched=install.cmd',
  'PostInstallCmd=<None>',
  'AdminQuietInstCmd=',
  'UserQuietInstCmd=',
  'SourceFiles=SourceFiles',
  '',
  '[Strings]'
)
$payload = Get-ChildItem $staging -File | Sort-Object Name
for ($i = 0; $i -lt $payload.Count; $i++) { $sedLines += ('FILE{0}="{1}"' -f $i, $payload[$i].Name) }
$sedLines += ''
$sedLines += '[SourceFiles]'
$sedLines += "SourceFiles0=$staging\"
$sedLines += '[SourceFiles0]'
for ($i = 0; $i -lt $payload.Count; $i++) { $sedLines += ('%FILE{0}%=' -f $i) }
$sedPath = Join-Path $staging 'build.sed'
[IO.File]::WriteAllText($sedPath, ($sedLines -join "`r`n") + "`r`n", [Text.Encoding]::GetEncoding(936))
OK "SED 已生成($($payload.Count) 个文件): $sedPath"

# ---------- 4) 调 IExpress 构建 ----------
Step 'IExpress 构建中(捆绑 node.exe 时压缩 99MB 需 1~3 分钟)'
$ix = Join-Path $env:WINDIR 'System32\iexpress.exe'
if (-not (Test-Path $ix)) { throw "未找到 iexpress.exe(应内置于 Windows): $ix" }
$proc = Start-Process -FilePath $ix -ArgumentList "/N $sedPath" -PassThru -WindowStyle Hidden
$deadline = (Get-Date).AddMinutes(15)
$sec = 0
while (-not $proc.HasExited -and -not (Test-Path $exePath) -and (Get-Date) -lt $deadline) {
  Start-Sleep -Seconds 1
  $sec++
  if ($sec % 30 -eq 0) { Write-Host "  ...构建中 ($sec 秒)" -ForegroundColor DarkGray }
}
if (-not (Test-Path $exePath)) {
  if (-not $proc.HasExited) { try { $proc.Kill() } catch {} }
  throw "IExpress 构建失败或超时(可能弹了错误对话框)。SED 已保留: $sedPath"
}
for ($k = 0; $k -lt 60 -and -not $proc.HasExited; $k++) { Start-Sleep -Milliseconds 500 }
if (-not $proc.HasExited) { try { $proc.Kill() } catch {} }
$size = (Get-Item $exePath).Length
OK "构建完成: $exePath ($([math]::Round($size / 1MB, 1)) MB, 用时 $sec 秒)"

# ---------- 5) 拷到 dist 并收尾 ----------
Step '输出到 dist\'
$dist = Join-Path $root 'dist'
if (-not (Test-Path $dist)) { New-Item -ItemType Directory -Path $dist | Out-Null }
$final = Join-Path $dist 'iflytek-sinkhole-setup.exe'
Copy-Item $exePath $final -Force
if (-not $NoRuntime -and $size -lt 10MB) { Warn '成品 <10MB:确认 node.exe 是否真的被打进去了' }
if ($KeepStaging) { Warn "暂存目录保留: $staging" }
else { Remove-Item $staging -Recurse -Force -ErrorAction SilentlyContinue }
Write-Host ''
Write-Host "  安装包: $final" -ForegroundColor Green
Write-Host "  大小:   $([math]::Round((Get-Item $final).Length / 1MB, 1)) MB" -ForegroundColor Green
Write-Host '  双击即装(自动 UAC 提权 → 铺文件 → 跑 setup-on-this-pc.ps1);' -ForegroundColor Cyan
Write-Host '  测试用环境变量: INSTALL_DIR=目录 SKIP_SETUP=1 AUTO_EXIT=1' -ForegroundColor Cyan
Write-Host ''
